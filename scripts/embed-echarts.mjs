// Deterministically embed the pinned vendored source. No download at build/runtime.
import fs from 'node:fs';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root = new URL('../', import.meta.url);
const asset = fs.readFileSync(new URL('assets/echarts.min.js', root));
const sha = crypto.createHash('sha256').update(asset).digest('hex');
const expected = 'bf4a223524e40b77c304bec67e1222cf551f14880cf42c69dc046558e11c07b1';
if (sha !== expected) throw Error('Vendored ECharts SHA-256 differs from pinned 5.6.0; review the resource and update its metadata together.');
const text = new TextDecoder('utf-8', {fatal:true}).decode(asset);
// Bound source columns (the compiler warns beyond 65535); the original bytes are
// rejoined without inserted whitespace, including the original license banners.
const chunks = [];
for (let i = 0; i < text.length; i += 4000) chunks.push(text.slice(i, i + 4000));
const generated = `// Generated by node scripts/embed-echarts.mjs. DO NOT EDIT.\n// Apache ECharts 5.6.0; Apache-2.0. Original license/NOTICE banners retained below.\n// Source: assets/echarts.min.js; SHA-256: ${sha}\n// See assets/README.md, assets/ECHARTS-LICENSE.txt and assets/ECHARTS-NOTICE.txt.\n\n///|\nfn vendored_echarts() -> String {\n  let out = StringBuilder(size_hint=${text.length})\n${chunks.map(chunk => `  out.write_string(\n    ${JSON.stringify(chunk)},\n  )`).join('\n')}\n  out.to_string()\n}\n`;
const target = new URL('cmd/main/echarts_generated.mbt', root);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replaceAll('\r\n','\n') !== generated) throw Error('Embedded source is stale. Run node scripts/embed-echarts.mjs.');
} else fs.writeFileSync(target, generated);
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${fileURLToPath(target)} (${asset.length} source bytes, SHA-256 ${sha})`);
